  @override
  List<String> getCategories() {
    final categories = <String>["الكل"];
    for (final topic in _topics) {
      if (!categories.contains(topic.category)) {
        categories.add(topic.category);
      }
    }
    return categories;
  }

  @override
  ProphetTopic? getTopicById(String id) {
    try {
      return _topics.firstWhere((t) => t.id == id);
    } catch (_) {
      return null;
    }
